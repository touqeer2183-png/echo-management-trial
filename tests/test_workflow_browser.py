    def test_print_waits_for_images_and_long_report_continues(self):
        patient, visit = self.encounter()
        self.ok('report/finalize', {'id':visit['id'],'report':self.report()}, 'operator')
        origin=f'http://127.0.0.1:{self.server.server_port}'
        with sync_playwright() as pw:
            browser=pw.chromium.launch(headless=True)
            ctx=browser.new_context()
            key,value=self.cookies['operator'].split('=',1)
            ctx.add_cookies([{'name':key,'value':value,'url':origin}])
            page=ctx.new_page();page.goto(origin);page.wait_for_selector('#logout')
            page.evaluate('() => {window.printCalls=0; window.print=()=>{window.printCalls++};}')
            page.evaluate('openEncounter(state.history[0])');page.wait_for_selector('#printReport')
            page.route('**/assets/logo-right.png',lambda route:route.abort())
            page.locator('#printReport').click()
            page.wait_for_function('document.querySelector("#toast").textContent.includes("could not load")')
            self.assertEqual(page.evaluate('window.printCalls'),0)
            page.unroute('**/assets/logo-right.png')
            page.locator('#printReport').click();page.wait_for_function('window.printCalls===1')
            page.evaluate("() => {const r=JSON.parse(visit.report); r.findings=Array.from({length:100},(_,i)=>'Manual report line '+(i+1)).join('\\n');visit.report=JSON.stringify(r);}")
            page.locator('#printReport').click();page.wait_for_function('window.printCalls===2')
            page.evaluate("document.body.classList.add('printing-report')")
            pdf=page.pdf(path='artifacts/workflow-long-report.pdf',prefer_css_page_size=True)
            self.assertGreater(len(re.findall(rb'/Type /Page\b',pdf)),1)
            self.assertIn('Manual report line 100',page.locator('#print').text_content())
            browser.close()
