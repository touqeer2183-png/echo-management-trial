    def test_previous_report_preview_preserves_current_inputs(self):
        patient, previous = self.encounter()
        self.ok('report/finalize', {'id': previous['id'], 'report': self.report()}, 'operator')
        self.ok('permission', {'patient_id': patient['id'], 'reason': 'Repeat assessment'}, 'operator')
        current = self.ok('token', {'patient_id': patient['id']}, 'receptionist')
        self.ok('claim', {'id': current['id']}, 'operator2')
        origin = f'http://127.0.0.1:{self.server.server_port}'
        with sync_playwright() as pw:
            browser = pw.chromium.launch(headless=True)
            ctx = browser.new_context(viewport={'width': 1500, 'height': 1050})
            key, value = self.cookies['operator2'].split('=', 1)
            ctx.add_cookies([{'name': key, 'value': value, 'url': origin}])
            page = ctx.new_page()
            page.goto(origin)
            page.wait_for_selector('#logout')
            page.evaluate('id => openEncounter({id, patient_id: ' + str(patient['id']) + '})', current['id'])
            page.wait_for_selector('#doctor')
            page.locator('[data-measure="EF"]').fill('57')
            page.locator('#conclusion').fill('Unsaved current conclusion')
            page.locator('[data-preview-echo]').click()
            self.assertIn('Manual test conclusion', page.locator('dialog').text_content())
            self.assertNotIn('Unsaved current conclusion', page.locator('dialog').text_content())
            page.screenshot(path='artifacts/previous-report-preview.png')
            page.get_by_role('button', name='Close Preview').click()
            self.assertEqual(page.locator('[data-measure="EF"]').input_value(), '57')
            self.assertEqual(page.locator('#conclusion').input_value(), 'Unsaved current conclusion')
            self.assertEqual(page.evaluate('visit.id'), current['id'])
            page.locator('#recordBack').click()
            page.locator('[data-view]').click()
            self.assertIn('Manual test conclusion', page.locator('dialog').text_content())
            page.keyboard.press('Escape')
            page.locator('dialog').wait_for(state='detached')
            self.assertEqual(page.locator('dialog').count(), 0)
            browser.close()

